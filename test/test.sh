#!/bin/sh
# Host tests for common/ (the verifier the app and the helper share) and the helper's import of
# kia.store's record, on the host JVM with the pinned Kotlin from the menu repo's fetch-tools.sh.
# Uses the index repo's (cabinwright/apps) signing test vectors, so both sides check the same bytes.
#   CABINWRIGHT_APPS=<path to the apps checkout>   default ../../apps
#   CABINWRIGHT_MENU=<path to the menu checkout>   default ../../menu
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$HERE/..
VECTORS=${CABINWRIGHT_APPS:-$ROOT/../apps}/tests/vectors
CABINWRIGHT_MENU=${CABINWRIGHT_MENU:-$ROOT/../menu}
JDK=${JAVA_HOME:-$(/usr/libexec/java_home -v 11)}
FT=$(sh "$CABINWRIGHT_MENU/api/tools/fetch-tools.sh")
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT
# Keys.kt is generated by build.sh, so a stand-in here
mkdir -p "$OUT/gen" "$OUT/classes"
printf 'package dev.cabinwright.store.common\n\nobject Keys {\n    val RELEASE = arrayOf<Pair<String, String>>()\n    val TEST = RELEASE\n}\n' \
    >"$OUT/gen/Keys.kt"
find "$ROOT/common/src" "$ROOT/helper/src" "$HERE/src" "$OUT/gen" -name '*.kt' >"$OUT/sources.txt"
# the host JDK here (java.nio.file for the vectors), where the builds only see Android 4.4's classes
JAVA_HOME=$JDK "$FT/kotlinc/bin/kotlinc" -jvm-target 1.8 -no-reflect -Werror -d "$OUT/classes" "@$OUT/sources.txt"
"$JDK/bin/java" -cp "$OUT/classes:$FT/kotlinc/lib/kotlin-stdlib.jar" dev.cabinwright.store.test.CommonTest "$VECTORS"
