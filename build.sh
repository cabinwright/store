#!/bin/sh
# Builds the cabinwright.store NEMESIS package: the App Store app (app/, on Cabinwright's API, so it
# shows up in All Menus) and the install helper (helper/, a dex run as root by
# package/svc/helper.sh). Both are Kotlin, compiled against Android 4.4's android.jar and
# shrunk by R8, and both compile in common/ (index verification) and the pinned index keys
# from keys/*.pub.pem. The tools (Kotlin, R8, android-19.jar) come from the menu checkout's
# api/tools/fetch-tools.sh.
#   DEBUG=1 ./build.sh   also pins keys/test/*.pub.pem, for a debug index (tools/debug-index.py)
#   CABINWRIGHT_MENU=<menu checkout>   default ../menu
# Writes dist/cabinwright.store.zip, and R8's name maps for reading stack traces (retrace):
# dist/cabinwright.store.map (the app) and dist/cabinwright.store.helper.map (the helper).
# Install over ADB:
#   adb push dist/cabinwright.store.zip /data/local/tmp/
#   adb shell "nemesis install --update /data/local/tmp/cabinwright.store.zip"
set -e
ROOT=$(cd "$(dirname "$0")" && pwd)
CABINWRIGHT_MENU=${CABINWRIGHT_MENU:-$ROOT/../menu}
TOOLS=$CABINWRIGHT_MENU/api/tools
JDK=${JAVA_HOME:-$(/usr/libexec/java_home -v 11)}
FT=$(sh "$TOOLS/fetch-tools.sh")
JAR=$FT/android-19.jar   # the head unit's API level: anything newer won't compile
STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT

# pinned keys -> Keys.kt
pins() {
    for pem in "$@"; do
        [ -f "$pem" ] || continue
        id=$(basename "$pem" .pub.pem)
        b64=$(grep -v -- ----- "$pem" | tr -d '\n\r ')
        printf '        "%s" to "%s",\n' "$id" "$b64"
    done
}
GEN=$STAGE/gen/dev/cabinwright/store/common
mkdir -p "$GEN"
TEST_PINS=
if [ "${DEBUG:-0}" = 1 ]; then
    TEST_PINS=$(pins "$ROOT"/keys/test/*.pub.pem)
fi
cat >"$GEN/Keys.kt" <<KEYS
package dev.cabinwright.store.common

/** Pinned index signing keys (generated by build.sh from keys/). */
object Keys {
    /** Keys that sign the published index. */
    val RELEASE: Array<Pair<String, String>> = arrayOf(
$(pins "$ROOT"/keys/*.pub.pem)
    )

    /** Test keys: only in DEBUG=1 builds, and only for a debug index. */
    val TEST: Array<Pair<String, String>> = arrayOf(
$TEST_PINS
    )
}
KEYS
grep -q '" to "' "$GEN/Keys.kt" || { echo "no keys in $ROOT/keys" >&2; exit 1; }
mkdir -p "$ROOT/dist"

# the app: the menu repo's build-app.sh takes one source tree, so stage app + common + keys
mkdir -p "$STAGE/app" "$STAGE/pkg/app"
cp -R "$ROOT/app/." "$STAGE/app/"
cp -R "$ROOT/common/src/." "$STAGE/app/src/"
cp -R "$STAGE/gen/." "$STAGE/app/src/"
CABINWRIGHT_MAP=$ROOT/dist/cabinwright.store.map \
    sh "$TOOLS/build-app.sh" --ui "$STAGE/app" "$STAGE/pkg/app/store.apk" >/dev/null

# the helper: no framework classes, as a dex in a jar for dalvikvm. Compiled against
# android-19.jar too, so it only uses the Java classes Android 4.4 has; Kotlin's stdlib is
# shrunk into it by R8 (main is kept by name: helper.sh starts it)
H=$STAGE/helper
mkdir -p "$H/classes" "$H/dex"
find "$ROOT/helper/src" "$ROOT/common/src" "$STAGE/gen" -name '*.kt' >"$H/kt.txt"
JAVA_HOME=$JDK "$FT/kotlinc/bin/kotlinc" -jvm-target 1.8 -no-jdk -no-reflect -Werror \
    -Xno-param-assertions -Xno-call-assertions -Xno-receiver-assertions \
    -classpath "$JAR" -d "$H/classes" "@$H/kt.txt"
(cd "$H/classes" && "$JDK/bin/jar" cfM ../classes.jar .)
"$JDK/bin/java" -cp "$FT/r8.jar" com.android.tools.r8.R8 --release --min-api 19 --lib "$JAR" \
    --pg-conf "$TOOLS/app-rules.pro" --pg-conf "$ROOT/helper/proguard-rules.pro" \
    --pg-map-output "$ROOT/dist/cabinwright.store.helper.map" --output "$H/dex" \
    "$H/classes.jar" "$FT/kotlinc/lib/kotlin-stdlib.jar"

cp -R "$ROOT/package/." "$STAGE/pkg/"
(cd "$H/dex" && zip -qX "$STAGE/pkg/svc/helper.jar" classes.dex)
rm -f "$ROOT/dist/cabinwright.store.zip"
(cd "$STAGE/pkg" && zip -qrX "$ROOT/dist/cabinwright.store.zip" .)
echo "$ROOT/dist/cabinwright.store.zip"
