#!/bin/sh
# Builds the cabinwright.store NEMESIS package: the App Store app (app/, on Cabinwright's API, so it
# shows up in All Menus) and the install helper (helper/, a dex run as root by
# package/svc/helper.sh). Both compile in common/ (index verification) and the pinned
# index keys from keys/*.pub.pem.
#   DEBUG=1 ./build.sh   also pins keys/test/*.pub.pem, for a debug index (tools/debug-index.py)
# Install over ADB:
#   adb push dist/cabinwright.store.zip /data/local/tmp/
#   adb shell "nemesis install --update /data/local/tmp/cabinwright.store.zip"
set -e
ROOT=$(cd "$(dirname "$0")" && pwd)
CABINWRIGHT_MENU=${CABINWRIGHT_MENU:-$ROOT/../menu}
SDK=${ANDROID_HOME:-$HOME/Library/Android/sdk}
BT=$SDK/build-tools/${BUILD_TOOLS:-29.0.2}
JAR=$SDK/platforms/android-23/android.jar   # compile against 23, use only API 19 calls
JDK=${JAVA_HOME:-$(/usr/libexec/java_home -v 11)}
STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT

# pinned keys -> Keys.java
pins() {
    for pem in "$@"; do
        [ -f "$pem" ] || continue
        id=$(basename "$pem" .pub.pem)
        b64=$(grep -v -- ----- "$pem" | tr -d '\n\r ')
        printf '        { "%s", "%s" },\n' "$id" "$b64"
    done
}
GEN=$STAGE/gen/dev/cabinwright/store/common
mkdir -p "$GEN"
TEST_PINS= DEBUG_BUILD=false
if [ "${DEBUG:-0}" = 1 ]; then
    TEST_PINS=$(pins "$ROOT"/keys/test/*.pub.pem) DEBUG_BUILD=true
fi
cat > "$GEN/Keys.java" <<EOF
package dev.cabinwright.store.common;

/** Pinned index signing keys (generated by build.sh from keys/). */
public final class Keys {
    /** Keys that sign the published index. */
    public static final String[][] RELEASE = {
$(pins "$ROOT"/keys/*.pub.pem)
    };
    /** Test keys: only in DEBUG=1 builds, and only for a debug index. */
    public static final String[][] TEST = {
$TEST_PINS
    };
    public static final boolean DEBUG_BUILD = $DEBUG_BUILD;

    private Keys() {
    }
}
EOF
grep -q '{ "' "$GEN/Keys.java" || { echo "no keys in $ROOT/keys" >&2; exit 1; }

# the app: the menu repo's build-app.sh takes one source tree, so stage app + common + keys
mkdir -p "$STAGE/app" "$STAGE/pkg/app"
cp -R "$ROOT/app/." "$STAGE/app/"
cp -R "$ROOT/common/src/." "$STAGE/app/src/"
cp -R "$STAGE/gen/." "$STAGE/app/src/"
sh "$CABINWRIGHT_MENU/api/tools/build-app.sh" --ui "$STAGE/app" "$STAGE/pkg/app/store.apk" >/dev/null

# the helper: plain Java, no framework classes, as a dex in a jar for dalvikvm
mkdir -p "$STAGE/helper/classes" "$STAGE/helper/dex"
"$JDK/bin/javac" -source 8 -target 8 -bootclasspath "$JAR" -Xlint:-options -d "$STAGE/helper/classes" \
    $(find "$ROOT/helper/src" "$ROOT/common/src" "$STAGE/gen" -name '*.java')
"$BT/d8" --release --min-api 19 --lib "$JAR" --output "$STAGE/helper/dex" \
    $(find "$STAGE/helper/classes" -name '*.class')

cp -R "$ROOT/package/." "$STAGE/pkg/"
(cd "$STAGE/helper/dex" && zip -qX "$STAGE/pkg/svc/helper.jar" classes.dex)
mkdir -p "$ROOT/dist" && rm -f "$ROOT/dist/cabinwright.store.zip"
(cd "$STAGE/pkg" && zip -qrX "$ROOT/dist/cabinwright.store.zip" .)
echo "$ROOT/dist/cabinwright.store.zip"
